import { test } from "node:test";
import assert from "node:assert/strict";
import { contractToPhysical } from "../../src/migrate/contract-to-physical.ts";
import { diffSchemas, emptyRenames } from "../../src/migrate/diff.ts";
import { emptyPhysical } from "../../src/migrate/physical.ts";
import type { PhysicalSchema, PhysicalTable } from "../../src/migrate/physical.ts";
import { blogContract, col, contract, model, rel } from "./fixtures.ts";

function table(name: string, over: Partial<PhysicalTable> = {}): PhysicalTable {
  return {
    name,
    columns: [{ name: "ID", type: "INTEGER", nullable: false }],
    primaryKey: { name: `PK_${name}`, columns: ["ID"] },
    uniques: [],
    indexes: [],
    foreignKeys: [],
    ...over,
  };
}

function schema(...tables: PhysicalTable[]): PhysicalSchema {
  return { tables: Object.fromEntries(tables.map((t) => [t.schema ? `${t.schema}.${t.name}` : t.name, t])) };
}

test("create tables from an empty database: SQL snapshot and ordering", () => {
  const ops = diffSchemas(emptyPhysical(), contractToPhysical(blogContract()));
  assert.deepEqual(
    ops.map((o) => o.kind),
    ["createTable", "createTable", "createIndex", "addForeignKey"],
  );
  assert.equal(
    ops[0]!.sql[0],
    [
      'CREATE COLUMN TABLE "POSTS" (',
      '  "ID" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,',
      '  "TITLE" NVARCHAR(200) NOT NULL,',
      '  "PUBLISHED" BOOLEAN DEFAULT FALSE NOT NULL,',
      '  "AUTHOR_ID" INTEGER NOT NULL,',
      '  CONSTRAINT "PK_POSTS" PRIMARY KEY ("ID")',
      ")",
    ].join("\n"),
  );
  assert.equal(
    ops[1]!.sql[0],
    [
      'CREATE COLUMN TABLE "USERS" (',
      '  "ID" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,',
      '  "EMAIL" NVARCHAR(255) NOT NULL,',
      '  "NAME" NVARCHAR(5000),',
      '  "CREATED_AT" TIMESTAMP DEFAULT CURRENT_UTCTIMESTAMP NOT NULL,',
      '  CONSTRAINT "PK_USERS" PRIMARY KEY ("ID"),',
      '  CONSTRAINT "UQ_USERS_EMAIL" UNIQUE ("EMAIL")',
      ")",
    ].join("\n"),
  );
  assert.equal(ops[2]!.sql[0], 'CREATE INDEX "IX_POSTS_AUTHOR_ID" ON "POSTS" ("AUTHOR_ID")');
  assert.equal(
    ops[3]!.sql[0],
    'ALTER TABLE "POSTS" ADD CONSTRAINT "FK_POSTS_AUTHOR_ID" FOREIGN KEY ("AUTHOR_ID") REFERENCES "USERS" ("ID") ON UPDATE RESTRICT ON DELETE CASCADE',
  );
  assert.ok(ops.every((o) => !o.destructive));
  assert.deepEqual(ops[0]!.precheck, {
    description: 'table "POSTS" does not exist yet',
    sql: "SELECT 1 FROM SYS.TABLES WHERE SCHEMA_NAME = CURRENT_SCHEMA AND TABLE_NAME = ?",
    params: ["POSTS"],
    expect: "empty",
  });
  assert.equal(ops[0]!.postcheck?.expect, "nonEmpty");
});

test("identical schemas produce no ops", () => {
  const p = contractToPhysical(blogContract());
  assert.deepEqual(diffSchemas(p, structuredClone(p)), []);
});

test("diff is deterministic regardless of input key order", () => {
  const p = contractToPhysical(blogContract());
  const reversed: PhysicalSchema = { tables: Object.fromEntries(Object.entries(p.tables).reverse()) };
  assert.deepEqual(diffSchemas(emptyPhysical(), p), diffSchemas(emptyPhysical(), reversed));
});

test("add column: nullable, with default, and NOT NULL without default (precheck empty table)", () => {
  const from = schema(table("USERS"));
  const to = schema(
    table("USERS", {
      columns: [
        { name: "ID", type: "INTEGER", nullable: false },
        { name: "AGE", type: "INTEGER", nullable: true },
        { name: "ROLE", type: "NVARCHAR(20)", nullable: false, default: "'member'" },
        { name: "CODE", type: "NVARCHAR(10)", nullable: false },
      ],
    }),
  );
  const ops = diffSchemas(from, to);
  assert.deepEqual(
    ops.map((o) => o.sql[0]),
    [
      'ALTER TABLE "USERS" ADD ("AGE" INTEGER)',
      'ALTER TABLE "USERS" ADD ("CODE" NVARCHAR(10) NOT NULL)',
      `ALTER TABLE "USERS" ADD ("ROLE" NVARCHAR(20) DEFAULT 'member' NOT NULL)`,
    ],
  );
  assert.equal(ops[1]!.precheck?.sql, 'SELECT 1 FROM "USERS" LIMIT 1');
  assert.equal(ops[0]!.precheck, undefined);
  assert.ok(ops.every((o) => !o.destructive));
});

test("drop column and drop table are destructive", () => {
  const from = schema(table("USERS", { columns: [{ name: "ID", type: "INTEGER", nullable: false }, { name: "AGE", type: "INTEGER", nullable: true }] }), table("OLD"));
  const to = schema(table("USERS"));
  const ops = diffSchemas(from, to);
  assert.deepEqual(
    ops.map((o) => [o.kind, o.sql[0], o.destructive]),
    [
      ["dropTable", 'DROP TABLE "OLD"', true],
      ["dropColumn", 'ALTER TABLE "USERS" DROP ("AGE")', true],
    ],
  );
});

test("rename table and column instead of drop + create", () => {
  const from = schema(table("USERS", { columns: [{ name: "ID", type: "INTEGER", nullable: false }, { name: "MAIL", type: "NVARCHAR(255)", nullable: false }] }));
  const to = schema(
    table("APP_USERS", {
      primaryKey: { name: "PK_USERS", columns: ["ID"] },
      columns: [{ name: "ID", type: "INTEGER", nullable: false }, { name: "EMAIL", type: "NVARCHAR(255)", nullable: false }],
    }),
  );
  const ops = diffSchemas(from, to, { renames: { tables: { USERS: "APP_USERS" }, columns: { APP_USERS: { MAIL: "EMAIL" } } } });
  assert.deepEqual(
    ops.map((o) => o.sql[0]),
    ['RENAME TABLE "USERS" TO "APP_USERS"', 'RENAME COLUMN "APP_USERS"."MAIL" TO "EMAIL"'],
  );
  assert.ok(ops.every((o) => !o.destructive));
});

test("rename keeps foreign keys that point at the renamed table", () => {
  const from = schema(
    table("USERS"),
    table("POSTS", {
      columns: [{ name: "ID", type: "INTEGER", nullable: false }, { name: "AUTHOR_ID", type: "INTEGER", nullable: false }],
      foreignKeys: [{ name: "FK_P", columns: ["AUTHOR_ID"], refTable: "USERS", refColumns: ["ID"], onDelete: "CASCADE", onUpdate: "RESTRICT" }],
    }),
  );
  const to = structuredClone(from);
  to.tables["MEMBERS"] = { ...to.tables["USERS"]!, name: "MEMBERS" };
  delete to.tables["USERS"];
  to.tables["POSTS"]!.foreignKeys[0]!.refTable = "MEMBERS";
  const ops = diffSchemas(from, to, { renames: { tables: { USERS: "MEMBERS" }, columns: {} } });
  assert.deepEqual(ops.map((o) => o.kind), ["renameTable"]);
});

test("invalid renames are ignored (falls back to drop + create)", () => {
  const from = schema(table("A"));
  const to = schema(table("B", { schema: "OTHER" }));
  const ops = diffSchemas(from, to, { renames: { tables: { A: "OTHER.B" }, columns: {} } });
  assert.deepEqual(ops.map((o) => o.kind), ["dropTable", "createTable"]);
});

test("type changes: widening is safe, narrowing and incompatible are destructive", () => {
  const mk = (type: string, nullable = true): PhysicalSchema =>
    schema(table("T", { columns: [{ name: "ID", type: "INTEGER", nullable: false }, { name: "C", type, nullable }] }));
  const widen = diffSchemas(mk("NVARCHAR(50)"), mk("NVARCHAR(100)"));
  assert.equal(widen.length, 1);
  assert.equal(widen[0]!.sql[0], 'ALTER TABLE "T" ALTER ("C" NVARCHAR(100) NULL)');
  assert.equal(widen[0]!.destructive, undefined);
  assert.match(widen[0]!.description, /NVARCHAR\(50\) → NVARCHAR\(100\)/);

  const narrow = diffSchemas(mk("NVARCHAR(100)"), mk("NVARCHAR(50)"));
  assert.equal(narrow[0]!.destructive, true);
  assert.match(narrow[0]!.description, /narrowing/);

  assert.equal(diffSchemas(mk("INTEGER"), mk("BIGINT"))[0]!.destructive, undefined);
  assert.equal(diffSchemas(mk("BIGINT"), mk("INTEGER"))[0]!.destructive, true);
  assert.equal(diffSchemas(mk("DECIMAL(10,2)"), mk("DECIMAL(12,2)"))[0]!.destructive, undefined);
  assert.equal(diffSchemas(mk("DECIMAL(10,2)"), mk("DECIMAL(10,4)"))[0]!.destructive, true);
  assert.equal(diffSchemas(mk("INTEGER"), mk("NVARCHAR(10)"))[0]!.destructive, true);
  assert.deepEqual(diffSchemas(mk("nvarchar( 50 )"), mk("NVARCHAR(50)")), []);
});

test("nullability: nullable → NOT NULL is destructive with a no-NULLs precheck", () => {
  const mk = (nullable: boolean): PhysicalSchema => schema(table("T", { columns: [{ name: "ID", type: "INTEGER", nullable: false }, { name: "C", type: "INTEGER", nullable }] }));
  const tighten = diffSchemas(mk(true), mk(false));
  assert.equal(tighten[0]!.sql[0], 'ALTER TABLE "T" ALTER ("C" INTEGER NOT NULL)');
  assert.equal(tighten[0]!.destructive, true);
  assert.equal(tighten[0]!.precheck?.sql, 'SELECT 1 FROM "T" WHERE "C" IS NULL LIMIT 1');
  const relax = diffSchemas(mk(false), mk(true));
  assert.equal(relax[0]!.destructive, undefined);
  assert.equal(relax[0]!.sql[0], 'ALTER TABLE "T" ALTER ("C" INTEGER NULL)');
});

test("default change only", () => {
  const mk = (d?: string): PhysicalSchema =>
    schema(table("T", { columns: [{ name: "ID", type: "INTEGER", nullable: false }, { name: "C", type: "INTEGER", nullable: false, ...(d ? { default: d } : {}) }] }));
  const ops = diffSchemas(mk("1"), mk("2"));
  assert.equal(ops[0]!.sql[0], 'ALTER TABLE "T" ALTER ("C" INTEGER DEFAULT 2 NOT NULL)');
  assert.deepEqual(diffSchemas(mk("1.0"), mk("1")), []);
  assert.match(diffSchemas(mk("1"), mk())[0]!.description, /default removed/);
});

test("identity change re-creates the column (destructive)", () => {
  const mk = (identity: boolean): PhysicalSchema => schema(table("T", { columns: [{ name: "ID", type: "INTEGER", nullable: false, ...(identity ? { identity } : {}) }] }));
  const ops = diffSchemas(mk(false), mk(true));
  assert.equal(ops.length, 1);
  assert.equal(ops[0]!.kind, "alterColumn");
  assert.deepEqual(ops[0]!.sql, ['ALTER TABLE "T" DROP ("ID")', 'ALTER TABLE "T" ADD ("ID" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL)']);
  assert.equal(ops[0]!.destructive, true);
});

test("uniques and indexes: add, drop, change columns; names-only differences are ignored", () => {
  const base = { columns: [{ name: "ID", type: "INTEGER", nullable: false }, { name: "A", type: "INTEGER", nullable: false }, { name: "B", type: "INTEGER", nullable: false }] };
  const from = schema(table("T", { ...base, uniques: [{ name: "UQ_OLD", columns: ["A"] }], indexes: [{ name: "IX_1", columns: ["A"] }, { name: "IX_SYS", columns: ["B"] }] }));
  const to = schema(table("T", { ...base, uniques: [{ name: "UQ_NEW", columns: ["A", "B"] }], indexes: [{ name: "IX_1", columns: ["A", "B"] }, { name: "IX_RENAMED", columns: ["B"] }] }));
  const ops = diffSchemas(from, to);
  assert.deepEqual(
    ops.map((o) => o.sql[0]),
    [
      'DROP INDEX "IX_1"',
      'ALTER TABLE "T" DROP CONSTRAINT "UQ_OLD"',
      'ALTER TABLE "T" ADD CONSTRAINT "UQ_NEW" UNIQUE ("A", "B")',
      'CREATE INDEX "IX_1" ON "T" ("A", "B")',
    ],
  );
  const addUnique = ops.find((o) => o.kind === "addUnique")!;
  assert.match(addUnique.precheck!.sql, /GROUP BY "A", "B" HAVING COUNT\(\*\) > 1/);
});

test("indexes in another schema are dropped schema-qualified", () => {
  const from = schema(table("T", { schema: "S", indexes: [{ name: "IX", columns: ["ID"] }] }));
  const to = schema(table("T", { schema: "S" }));
  assert.equal(diffSchemas(from, to)[0]!.sql[0], 'DROP INDEX "S"."IX"');
});

test("primary key change: drop then add; system-generated names are not compared", () => {
  const cols = [{ name: "ID", type: "INTEGER", nullable: false }, { name: "K", type: "INTEGER", nullable: false }];
  const from = schema(table("T", { columns: cols, primaryKey: { name: "_SYS_TREE_CS_1", columns: ["ID"] } }));
  assert.deepEqual(diffSchemas(from, schema(table("T", { columns: cols, primaryKey: { name: "PK_T", columns: ["ID"] } }))), []);
  const ops = diffSchemas(from, schema(table("T", { columns: cols, primaryKey: { name: "PK_T", columns: ["ID", "K"] } })));
  assert.deepEqual(ops.map((o) => o.sql[0]), ['ALTER TABLE "T" DROP PRIMARY KEY', 'ALTER TABLE "T" ADD CONSTRAINT "PK_T" PRIMARY KEY ("ID", "K")']);
});

test("foreign keys: onDelete change re-creates the constraint; FKs are dropped first and added last", () => {
  const cols = [{ name: "ID", type: "INTEGER", nullable: false }, { name: "U", type: "INTEGER", nullable: true }];
  const fk = { name: "FK_T_U", columns: ["U"], refTable: "USERS", refColumns: ["ID"], onDelete: "RESTRICT" as const, onUpdate: "RESTRICT" as const };
  const from = schema(table("USERS"), table("T", { columns: cols, foreignKeys: [fk] }));
  const to = schema(table("USERS"), table("T", { columns: [...cols, { name: "X", type: "INTEGER", nullable: true }], foreignKeys: [{ ...fk, onDelete: "SET NULL" }] }));
  const ops = diffSchemas(from, to);
  assert.deepEqual(ops.map((o) => o.kind), ["dropForeignKey", "addColumn", "addForeignKey"]);
  assert.equal(ops[2]!.sql[0], 'ALTER TABLE "T" ADD CONSTRAINT "FK_T_U" FOREIGN KEY ("U") REFERENCES "USERS" ("ID") ON UPDATE RESTRICT ON DELETE SET NULL');
});

test("dropping two tables that reference each other drops the foreign keys before the tables", () => {
  const a = table("A", { columns: [{ name: "ID", type: "INTEGER", nullable: false }, { name: "B_ID", type: "INTEGER", nullable: true }], foreignKeys: [{ name: "FK_A_B", columns: ["B_ID"], refTable: "B", refColumns: ["ID"], onDelete: "RESTRICT", onUpdate: "RESTRICT" }] });
  const b = table("B", { columns: [{ name: "ID", type: "INTEGER", nullable: false }, { name: "A_ID", type: "INTEGER", nullable: true }], foreignKeys: [{ name: "FK_B_A", columns: ["A_ID"], refTable: "A", refColumns: ["ID"], onDelete: "RESTRICT", onUpdate: "RESTRICT" }] });
  const ops = diffSchemas(schema(a, b), emptyPhysical());
  assert.deepEqual(ops.map((o) => o.kind), ["dropForeignKey", "dropForeignKey", "dropTable", "dropTable"]);
});

test("retyping a column used by a foreign key re-creates that foreign key", () => {
  const users = (t: string): PhysicalTable => table("USERS", { columns: [{ name: "ID", type: t, nullable: false }] });
  const posts = (t: string): PhysicalTable =>
    table("POSTS", {
      columns: [{ name: "ID", type: "INTEGER", nullable: false }, { name: "U", type: t, nullable: false }],
      foreignKeys: [{ name: "FK", columns: ["U"], refTable: "USERS", refColumns: ["ID"], onDelete: "RESTRICT", onUpdate: "RESTRICT" }],
    });
  const ops = diffSchemas(schema(users("INTEGER"), posts("INTEGER")), schema(users("BIGINT"), posts("BIGINT")));
  assert.deepEqual(ops.map((o) => o.kind), ["dropForeignKey", "alterColumn", "alterColumn", "addForeignKey"]);
});

test("models in another schema are qualified; @@schema equal to the default schema is not", () => {
  const c = contract([
    model("A", [col("id", "Int", { id: true })], { schema: "SALES" }),
    model("B", [col("id", "Int", { id: true })], { schema: "APP" }),
    model("V", [col("id", "Int")], { kind: "view" }),
  ]);
  const p = contractToPhysical(c, { defaultSchema: "APP" });
  assert.deepEqual(Object.keys(p.tables).sort(), ["B", "SALES.A"]);
  const ops = diffSchemas(emptyPhysical(), p);
  assert.ok(ops[1]!.sql[0]!.startsWith('CREATE COLUMN TABLE "SALES"."A"'));
  assert.deepEqual(ops[1]!.precheck?.params, ["SALES", "A"]);
});

test("emptyRenames and relation fields without FK produce nothing extra", () => {
  const c = contract([model("A", [col("id", "Int", { id: true }), rel("bs", "B", { list: true })]), model("B", [col("id", "Int", { id: true }), col("aId", "Int"), rel("a", "A", { fields: ["aId"], references: ["id"] })])]);
  const p = contractToPhysical(c);
  assert.equal(p.tables["B"]!.foreignKeys[0]!.name, "FK_B_aId");
  assert.deepEqual(diffSchemas(p, p, { renames: emptyRenames() }), []);
});
