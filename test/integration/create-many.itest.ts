// createMany / createManyAndReturn against real primary key and unique constraints.
//
// Runs DDL, so it only runs when HANA_ORM_ALLOW_DDL=1 (set it for a local/test database only,
// e.g. the docker-compose.hana.yml instance). It creates a fresh schema per run and drops it
// (CASCADE) at the end.
import { after, before, test } from "node:test";
import assert from "node:assert/strict";
import { HanaClient } from "../generated/constraints/index.ts";
import { DatabaseError } from "../../src/runtime/errors.ts";

if (process.env.HANA_ORM_ENV_FILE) process.loadEnvFile(process.env.HANA_ORM_ENV_FILE);
const enabled = process.env.HANA_ORM_ALLOW_DDL === "1" && Boolean(process.env.HANA_HOST);
const skip = enabled ? false : "set HANA_ORM_ALLOW_DDL=1 with a local/test HANA to run";

const schemaName = `HANA_ORM_IT_${Date.now().toString(36).toUpperCase()}_CM`;
const db = new HanaClient({ schema: schemaName });

before(async () => {
  if (!enabled) return;
  await db.$executeRawUnsafe(`CREATE SCHEMA "${schemaName}"`);
  await db.$executeRawUnsafe(`CREATE COLUMN TABLE "${schemaName}"."MEMBERS" (
    "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "email" NVARCHAR(200) NOT NULL UNIQUE,
    "name" NVARCHAR(100), "team" NVARCHAR(40) NOT NULL, "seat" INTEGER NOT NULL,
    "credit" DECIMAL(15,2) NOT NULL, UNIQUE ("team", "seat"))`);
  await db.$executeRawUnsafe(`CREATE COLUMN TABLE "${schemaName}"."BADGES" (
    "code" NVARCHAR(20) PRIMARY KEY, "label" NVARCHAR(100) NOT NULL, "MEMBER_ID" INTEGER NOT NULL)`);
});

after(async () => {
  if (!enabled) return;
  await db.$executeRawUnsafe(`DROP SCHEMA "${schemaName}" CASCADE`).catch(() => {});
  await db.$disconnect();
});

test("createMany without skipDuplicates fails on a duplicate and writes nothing", { skip }, async () => {
  await db.member.create({ data: { email: "a@example.com", team: "red", seat: 1 } });
  await assert.rejects(
    db.member.createMany({ data: [{ email: "b@example.com", team: "red", seat: 2 }, { email: "a@example.com", team: "red", seat: 3 }] }),
    DatabaseError,
  );
  assert.equal(await db.member.count(), 1);
});

test("createMany with skipDuplicates skips rows that match any unique, also within the batch", { skip }, async () => {
  const r = await db.member.createMany({
    skipDuplicates: true,
    data: [
      { email: "a@example.com", team: "blue", seat: 1 }, // existing email
      { email: "c@example.com", team: "red", seat: 1 }, // existing (team, seat)
      { email: "d@example.com", team: "blue", seat: 2 }, // new
      { email: "d@example.com", team: "blue", seat: 3 }, // same email as the row before
      { email: "e@example.com", name: "E", team: "green", seat: 1, credit: "2.50" }, // new, other column set
    ],
  });
  assert.deepEqual(r, { count: 2 });
  const rows = await db.member.findMany({ orderBy: { email: "asc" }, select: { email: true, team: true, seat: true, credit: true } });
  assert.deepEqual(rows, [
    { email: "a@example.com", team: "red", seat: 1, credit: "0.00" },
    { email: "d@example.com", team: "blue", seat: 2, credit: "0.00" },
    { email: "e@example.com", team: "green", seat: 1, credit: "2.50" },
  ]);
});

test("createManyAndReturn returns the inserted rows in input order with identity values", { skip }, async () => {
  const rows = await db.member.createManyAndReturn({
    data: [
      { email: "z@example.com", team: "gold", seat: 9 },
      { email: "y@example.com", team: "gold", seat: 8, name: "Y" },
    ],
  });
  assert.deepEqual(rows.map((r) => r.email), ["z@example.com", "y@example.com"]);
  assert.ok(rows.every((r) => typeof r.id === "number"));
  assert.ok(rows[1]!.id > rows[0]!.id);
  assert.equal(rows[1]!.name, "Y");
  assert.equal(rows[0]!.credit, "0.00");
});

test("createManyAndReturn with skipDuplicates returns only new rows; select, omit and include work", { skip }, async () => {
  const picked = await db.member.createManyAndReturn({
    skipDuplicates: true,
    data: [
      { email: "z@example.com", team: "x", seat: 1 }, // existing email
      { email: "x@example.com", team: "x", seat: 1 },
      { email: "w@example.com", team: "x", seat: 1 }, // duplicate (team, seat) of the row before
    ],
    select: { email: true },
  });
  assert.deepEqual(picked, [{ email: "x@example.com" }]);

  const x = await db.member.findUniqueOrThrow({ where: { email: "x@example.com" } });
  const badges = await db.badge.createManyAndReturn({
    skipDuplicates: true,
    data: [
      { code: "B1", label: "first", memberId: x.id },
      { code: "B1", label: "again", memberId: x.id },
      { code: "B2", label: "second", memberId: x.id },
    ],
    omit: { code: true },
    include: { member: { select: { email: true } } },
  });
  assert.deepEqual(badges, [
    { label: "first", memberId: x.id, member: { email: "x@example.com" } },
    { label: "second", memberId: x.id, member: { email: "x@example.com" } },
  ]);
  assert.deepEqual(await db.badge.createManyAndReturn({ skipDuplicates: true, data: [{ code: "B2", label: "dup", memberId: x.id }] }), []);
});

test("nested createMany accepts skipDuplicates", { skip }, async () => {
  const m = await db.member.create({
    data: { email: "n@example.com", team: "n", seat: 1, badges: { createMany: { skipDuplicates: true, data: [{ code: "N1", label: "a" }, { code: "N1", label: "b" }, { code: "B1", label: "taken" }] } } },
    include: { badges: true },
  });
  assert.deepEqual(m.badges.map((b) => [b.code, b.label]), [["N1", "a"]]);
});
