// End-to-end CLI test: plan → deploy → generate → query → change schema → plan → deploy → pull.
//
// Runs DDL, so it only runs when HANA_ORM_ALLOW_DDL=1 (set it for a local/test database only,
// e.g. the docker-compose.hana.yml instance). It creates a fresh schema per run and drops it
// (CASCADE) at the end.
import { after, before, test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, readdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { main } from "../../src/cli/index.ts";
import { HanaDriver } from "../../src/runtime/hana-driver.ts";
import { resolveConnectionConfig } from "../../src/runtime/config.ts";
import { DatabaseError } from "../../src/runtime/errors.ts";

if (process.env.HANA_ORM_ENV_FILE) process.loadEnvFile(process.env.HANA_ORM_ENV_FILE);
const enabled = process.env.HANA_ORM_ALLOW_DDL === "1" && Boolean(process.env.HANA_HOST);
const skip = enabled ? false : "set HANA_ORM_ALLOW_DDL=1 with a local/test HANA to run";

const schemaName = `HANA_ORM_IT_${Date.now().toString(36).toUpperCase()}`;
const dir = mkdtempSync(join(tmpdir(), "hana-orm-it-"));
const schemaFile = join(dir, "schema.hana");
const runtimeUrl = pathToFileURL(join(import.meta.dirname, "../../src/runtime/index.ts")).href;
let admin: HanaDriver;
const cwd = process.cwd();

const header = `datasource db {
  provider = "hana"
  schema   = env("HANA_ORM_IT_SCHEMA")
}

generator client {
  provider      = "hana-orm"
  output        = "./gen"
  runtimeImport = "${runtimeUrl}"
}
`;

const v1 = `${header}
enum Plan {
  FREE
  PRO
}

model Account {
  id        Int       @id @default(autoincrement())
  email     String    @unique @db.NVarChar(200)
  plan      Plan      @default(FREE)
  balance   Decimal   @default(0) @db.Decimal(15, 2)
  createdAt DateTime  @default(now()) @map("CREATED_AT")
  projects  Project[]

  @@map("ACCOUNTS")
}

model Project {
  id        Int     @id @default(autoincrement())
  name      String  @db.NVarChar(100)
  accountId Int     @map("ACCOUNT_ID")
  account   Account @relation(fields: [accountId], references: [id], onDelete: Cascade)

  @@unique([accountId, name])
  @@map("PROJECTS")
}
`;

// v2: new optional column, renamed column (@map change), new model, new index.
const v2 = v1
  .replace(`  plan      Plan      @default(FREE)`, `  plan      Plan      @default(FREE)\n  phone     String?   @db.NVarChar(30)`)
  .replace(`@map("CREATED_AT")`, `@map("CREATED_ON")`)
  .replace(`  @@unique([accountId, name])`, `  archived  Boolean @default(false)\n\n  @@unique([accountId, name])\n  @@index([archived])`)
  .concat(`
model AuditLog {
  id      BigInt   @id @default(autoincrement())
  message String   @db.NVarChar(500)
  at      DateTime @default(now())

  @@map("AUDIT_LOG")
}
`);

async function cli(...args: string[]): Promise<number> {
  process.chdir(dir);
  try {
    return await main([...args, "--schema", schemaFile]);
  } finally {
    process.chdir(cwd);
  }
}

before(async () => {
  if (!enabled) return;
  process.env.HANA_ORM_IT_SCHEMA = schemaName;
  admin = new HanaDriver(resolveConnectionConfig(undefined, { currentSchema: undefined }), { poolSize: 1 });
  await admin.execute(`CREATE SCHEMA "${schemaName}"`);
});

after(async () => {
  if (!enabled) return;
  await admin.execute(`DROP SCHEMA "${schemaName}" CASCADE`).catch(() => {});
  await admin.close();
  rmSync(dir, { recursive: true, force: true });
});

test("migrate plan + deploy creates the schema from scratch", { skip }, async () => {
  writeFileSync(schemaFile, v1);
  assert.equal(await cli("migrate", "plan", "--name", "init"), 0);
  const migrations = readdirSync(join(dir, "migrations"));
  assert.equal(migrations.length, 1);
  const sql = readFileSync(join(dir, "migrations", migrations[0]!, "migration.sql"), "utf8");
  assert.match(sql, /CREATE COLUMN TABLE/);
  assert.match(sql, /GENERATED BY DEFAULT AS IDENTITY/);
  assert.match(sql, /FOREIGN KEY/);
  assert.equal(await cli("migrate", "deploy"), 0);
  assert.equal(await cli("migrate", "status"), 0);
  assert.equal(await cli("db", "verify"), 0);
});

test("generated client works on the migrated tables", { skip }, async () => {
  assert.equal(await cli("generate"), 0);
  const { HanaClient } = await import(pathToFileURL(join(dir, "gen", "index.ts")).href);
  const db = new HanaClient({ poolSize: 2 });
  try {
    const a = await db.account.create({ data: { email: "a@example.com", plan: "PRO", projects: { create: [{ name: "alpha" }, { name: "beta" }] } }, include: { projects: true } });
    assert.equal(a.projects.length, 2);
    assert.equal(a.balance, "0.00");
    // real constraints exist here (unlike temporary tables)
    await assert.rejects(db.account.create({ data: { email: "a@example.com" } }), (e: unknown) => e instanceof DatabaseError && e.code === "UNIQUE_CONSTRAINT");
    await assert.rejects(db.project.create({ data: { name: "x", accountId: 999999 } }), (e: unknown) => e instanceof DatabaseError && e.code === "FOREIGN_KEY_CONSTRAINT");
    const p = await db.project.findUnique({ where: { accountId_name: { accountId: a.id, name: "beta" } } });
    assert.equal(p?.name, "beta");
  } finally {
    await db.$disconnect();
  }
});

test("schema changes become a second migration that keeps data", { skip }, async () => {
  writeFileSync(schemaFile, v2);
  assert.equal(await cli("migrate", "status"), 1, "status reports schema changes without a migration");
  assert.equal(await cli("migrate", "plan", "--name", "phone_audit"), 0);
  const second = readdirSync(join(dir, "migrations")).sort()[1]!;
  const sql = readFileSync(join(dir, "migrations", second, "migration.sql"), "utf8");
  assert.match(sql, /RENAME COLUMN/);
  assert.doesNotMatch(sql, /DROP/);
  assert.equal(await cli("migrate", "deploy"), 0);
  assert.equal(await cli("migrate", "status"), 0);

  const rows = await admin.query<{ E: string; C: unknown }>(`SELECT "email" AS "E", "CREATED_ON" AS "C" FROM "${schemaName}"."ACCOUNTS"`);
  assert.equal(rows.length, 1);
  assert.equal(rows[0]!.E, "a@example.com");
  assert.ok(rows[0]!.C, "renamed column kept its data");
});

test("destructive changes are refused without --allow-destructive", { skip }, async () => {
  writeFileSync(schemaFile, v2.replace(`  phone     String?   @db.NVarChar(30)\n`, ""));
  const warnings: string[] = [];
  const origWarn = console.warn;
  console.warn = (m: string) => warnings.push(m);
  try {
    assert.equal(await cli("migrate", "plan", "--name", "drop_phone"), 1);
  } finally {
    console.warn = origWarn;
  }
  assert.match(warnings.join(" "), /allow-destructive/, "refused because of the destructive change");
  assert.equal(readdirSync(join(dir, "migrations")).length, 2);
  writeFileSync(schemaFile, v2);
});

test("drift is detected when the database is changed by hand", { skip }, async () => {
  await admin.execute(`ALTER TABLE "${schemaName}"."ACCOUNTS" ADD ("NOTE" NVARCHAR(10))`);
  assert.equal(await cli("migrate", "status"), 1);
  await admin.execute(`ALTER TABLE "${schemaName}"."ACCOUNTS" DROP ("NOTE")`);
  assert.equal(await cli("migrate", "status"), 0);
});

test("renaming a unique constraint and moving a table to another schema keep the data", { skip }, async () => {
  const otherSchema = `${schemaName}_ARCH`;
  await admin.execute(`CREATE SCHEMA "${otherSchema}"`);
  try {
    await admin.execute(`INSERT INTO "${schemaName}"."AUDIT_LOG" ("message") VALUES ('kept')`);
    const v3 = v2
      .replace("  @@unique([accountId, name])", '  @@unique([accountId, name], map: "UQ_PROJECT_NAME")')
      .replace('  @@map("AUDIT_LOG")', `  @@map("AUDIT_LOG")
  @@schema("${otherSchema}")`);
    writeFileSync(schemaFile, v3);
    assert.equal(await cli("migrate", "plan", "--name", "move_audit"), 0);
    const third = readdirSync(join(dir, "migrations")).sort()[2]!;
    const sql = readFileSync(join(dir, "migrations", third, "migration.sql"), "utf8");
    // tables of the default schema stay unqualified and resolve against the connection's schema
    assert.ok(sql.includes(`RENAME TABLE "AUDIT_LOG" TO "${otherSchema}"."AUDIT_LOG"`), sql);
    assert.match(sql, /DROP CONSTRAINT/);
    assert.match(sql, /ADD CONSTRAINT "UQ_PROJECT_NAME" UNIQUE/);
    assert.equal(await cli("migrate", "deploy"), 0);
    assert.equal(await cli("migrate", "status"), 0);
    const moved = await admin.query<{ M: string }>(`SELECT "message" AS "M" FROM "${otherSchema}"."AUDIT_LOG"`);
    assert.deepEqual(moved.map((r) => r.M), ["kept"]);
    // move it back so the remaining tests see the original layout
    writeFileSync(schemaFile, v3.replace(`
  @@schema("${otherSchema}")`, ""));
    assert.equal(await cli("migrate", "plan", "--name", "move_back"), 0);
    assert.equal(await cli("migrate", "deploy"), 0);
  } finally {
    await admin.execute(`DROP SCHEMA "${otherSchema}" CASCADE`).catch(() => {});
  }
});

test("TypeScript data migrations run inside the migration transaction", { skip }, async () => {
  assert.equal(await cli("migrate", "plan", "--name", "fill_phone", "--empty", "--script"), 0);
  const folder = readdirSync(join(dir, "migrations")).sort().at(-1)!;
  writeFileSync(
    join(dir, "migrations", folder, "migration.ts"),
    `import type { MigrationScript } from "hana-orm/migrate";
const migration: MigrationScript = async ({ query, execute, log }) => {
  const rows = await query<{ ID: number }>('SELECT "id" AS "ID" FROM "ACCOUNTS" WHERE "phone" IS NULL');
  for (const r of rows) await execute('UPDATE "ACCOUNTS" SET "phone" = ? WHERE "id" = ?', ["+00-" + r.ID, r.ID]);
  log("filled " + rows.length);
};
export default migration;
`,
  );
  assert.equal(await cli("migrate", "deploy"), 0);
  const rows = await admin.query<{ P: string | null }>(`SELECT "phone" AS "P" FROM "${schemaName}"."ACCOUNTS"`);
  assert.ok(rows.length > 0 && rows.every((r) => r.P?.startsWith("+00-")), JSON.stringify(rows));

  // a failing script rolls back its migration, including statements it already ran
  assert.equal(await cli("migrate", "plan", "--name", "broken", "--empty", "--script"), 0);
  const broken = readdirSync(join(dir, "migrations")).sort().at(-1)!;
  writeFileSync(
    join(dir, "migrations", broken, "migration.ts"),
    `export default async ({ execute }: { execute: (s: string) => Promise<number> }) => {
  await execute('UPDATE "ACCOUNTS" SET "phone" = NULL');
  throw new Error("stop");
};
`,
  );
  assert.equal(await cli("migrate", "deploy"), 1);
  const after = await admin.query<{ P: string | null }>(`SELECT "phone" AS "P" FROM "${schemaName}"."ACCOUNTS"`);
  assert.ok(after.every((r) => r.P?.startsWith("+00-")), "rolled back");
  await cli("migrate", "resolve", "--rolled-back", broken);
  rmSync(join(dir, "migrations", broken), { recursive: true, force: true });
});

test("migrate reset drops the project's tables, re-applies migrations and seeds", { skip }, async () => {
  await admin.execute(`CREATE COLUMN TABLE "${schemaName}"."UNRELATED" ("ID" INTEGER PRIMARY KEY)`);
  await admin.execute(`INSERT INTO "${schemaName}"."UNRELATED" VALUES (1)`);
  const seedScript = join(dir, "seed.mjs");
  writeFileSync(seedScript, `import { writeFileSync } from "node:fs";\nwriteFileSync(${JSON.stringify(join(dir, "seeded.txt"))}, process.env.HANA_ORM_SCHEMA ?? "");\n`);
  writeFileSync(join(dir, "package.json"), JSON.stringify({ "hana-orm": { seed: `"${process.execPath}" "${seedScript}"` } }));

  assert.equal(await cli("migrate", "reset"), 1, "refuses without --force when it cannot ask");
  assert.equal((await admin.query(`SELECT 1 FROM "${schemaName}"."ACCOUNTS"`)).length, 1, "nothing was dropped");

  // the earlier "move_audit" migration moves a table into this schema and back
  await admin.execute(`CREATE SCHEMA "${schemaName}_ARCH"`);
  try {
    assert.equal(await cli("migrate", "reset", "--force"), 0);
  } finally {
    await admin.execute(`DROP SCHEMA "${schemaName}_ARCH" CASCADE`).catch(() => {});
  }
  assert.equal((await admin.query(`SELECT 1 FROM "${schemaName}"."ACCOUNTS"`)).length, 0, "data is gone");
  assert.equal((await admin.query(`SELECT 1 FROM "${schemaName}"."UNRELATED"`)).length, 1, "tables outside the project are kept");
  assert.equal(readFileSync(join(dir, "seeded.txt"), "utf8"), schemaFile);
  assert.equal(await cli("migrate", "status"), 0);
  rmSync(join(dir, "package.json"));
});

test("db pull reproduces an equivalent schema", { skip }, async () => {
  const pulledFile = join(dir, "pulled.hana");
  writeFileSync(pulledFile, header);
  process.chdir(dir);
  try {
    assert.equal(await main(["db", "pull", "--schema", pulledFile]), 0);
  } finally {
    process.chdir(cwd);
  }
  const pulled = readFileSync(pulledFile, "utf8");
  assert.match(pulled, /model Accounts \{/);
  assert.match(pulled, /@@map\("ACCOUNTS"\)/);
  assert.match(pulled, /@default\(autoincrement\(\)\)/);
  assert.doesNotMatch(pulled, /_HANA_ORM_/);
  process.chdir(dir);
  try {
    assert.equal(await main(["db", "push", "--dry-run", "--schema", pulledFile]), 0);
  } finally {
    process.chdir(cwd);
  }
});
