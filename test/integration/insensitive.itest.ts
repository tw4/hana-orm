// Case-insensitive filters on a real column table (issue #83).
//
// HANA may rewrite `LOWER(a) op LOWER(b)` on a column table into its own case-insensitive
// comparison, which does not match the Turkish 'İ' (U+0130) with 'i'. Local temporary tables do not
// show this, so the test needs a real table: it runs DDL and only runs with HANA_ORM_ALLOW_DDL=1
// (local/test database only). It creates a fresh schema and drops it (CASCADE) at the end.
import { after, before, test } from "node:test";
import assert from "node:assert/strict";
import { HanaClient, tables, ilike, type MemberWhereInput } from "../generated/constraints/index.ts";

if (process.env.HANA_ORM_ENV_FILE) process.loadEnvFile(process.env.HANA_ORM_ENV_FILE);
const enabled = process.env.HANA_ORM_ALLOW_DDL === "1" && Boolean(process.env.HANA_HOST);
const skip = enabled ? false : "set HANA_ORM_ALLOW_DDL=1 with a local/test HANA to run";

const schemaName = `HANA_ORM_IT_${Date.now().toString(36).toUpperCase()}_CI`;
const db = new HanaClient({ schema: schemaName });

before(async () => {
  if (!enabled) return;
  await db.$executeRawUnsafe(`CREATE SCHEMA "${schemaName}"`);
  await db.$executeRawUnsafe(`CREATE COLUMN TABLE "${schemaName}"."MEMBERS" (
    "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "email" NVARCHAR(200) NOT NULL UNIQUE,
    "name" NVARCHAR(100), "team" NVARCHAR(40) NOT NULL, "seat" INTEGER NOT NULL,
    "credit" DECIMAL(15,2) NOT NULL, UNIQUE ("team", "seat"))`);
  await db.member.createMany({
    data: [
      { email: "a@example.com", name: "File İptal", team: "t", seat: 1 },
      { email: "b@example.com", name: "File Revize", team: "t", seat: 2 },
      { email: "c@example.com", name: "İSTANBUL", team: "t", seat: 3 },
      { email: "d@example.com", name: "ΣΟΦΙΑΣ", team: "t", seat: 4 },
    ],
  });
  // move the rows from the delta into the main store, where the rewrite also applies
  await db.$executeRawUnsafe(`MERGE DELTA OF "${schemaName}"."MEMBERS"`);
});

after(async () => {
  if (!enabled) return;
  await db.$executeRawUnsafe(`DROP SCHEMA "${schemaName}" CASCADE`).catch(() => {});
  await db.$disconnect();
});

const names = async (where: MemberWhereInput) => (await db.member.findMany({ where, orderBy: { seat: "asc" }, select: { name: true } })).map((r) => r.name);

test("equals / in / not with mode insensitive match 'İ' and 'i'", { skip }, async () => {
  assert.deepEqual(await names({ name: { equals: "FILE İPTAL", mode: "insensitive" } }), ["File İptal"]);
  assert.deepEqual(await names({ name: { equals: "file iptal", mode: "insensitive" } }), ["File İptal"]);
  assert.deepEqual(await names({ name: { in: ["istanbul", "FILE REVIZE"], mode: "insensitive" } }), ["File Revize", "İSTANBUL"]);
  assert.deepEqual(await names({ name: { not: "file iptal", mode: "insensitive" } }), ["File Revize", "İSTANBUL", "ΣΟΦΙΑΣ"]);
});

test("contains / startsWith with mode insensitive match 'İ' and 'i'", { skip }, async () => {
  assert.deepEqual(await names({ name: { contains: "iptal", mode: "insensitive" } }), ["File İptal"]);
  assert.deepEqual(await names({ name: { contains: "İPTAL", mode: "insensitive" } }), ["File İptal"]);
  assert.deepEqual(await names({ name: { startsWith: "ist", mode: "insensitive" } }), ["İSTANBUL"]);
  assert.deepEqual(await names({ name: { equals: "σοφιας", mode: "insensitive" } }), ["ΣΟΦΙΑΣ"], "final sigma: both sides lowered by HANA");
});

test("ilike() in the query builder matches 'İ' and 'i'", { skip }, async () => {
  const m = tables.member;
  const rows = await db.select({ name: m.name }).from(m).where(ilike(m.name, "%iptal%"));
  assert.deepEqual(rows, [{ name: "File İptal" }]);
});
