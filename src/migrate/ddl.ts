/** HANA DDL text for physical objects. Identifiers are always quoted. */

import { quoteIdent } from "../runtime/sql.ts";
import type { Check } from "./ops.ts";
import type { PhysicalCheck, PhysicalColumn, PhysicalForeignKey, PhysicalSequence, PhysicalTable } from "./physical.ts";
import { sqlString } from "./types.ts";

export function physicalTableRef(t: { schema?: string; name: string }): string {
  return t.schema ? `${quoteIdent(t.schema)}.${quoteIdent(t.name)}` : quoteIdent(t.name);
}

export function columnList(columns: readonly string[]): string {
  return columns.map(quoteIdent).join(", ");
}

/** Column definition, e.g. `"ID" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL`. */
export function columnDefinition(c: PhysicalColumn, explicitNull = false): string {
  let s = `${quoteIdent(c.name)} ${c.type}`;
  if (c.default !== undefined && !c.identity) s += ` DEFAULT ${c.default}`;
  if (c.identity) s += " GENERATED BY DEFAULT AS IDENTITY";
  if (!c.nullable) s += " NOT NULL";
  else if (explicitNull) s += " NULL";
  return s;
}

export function createTableSql(t: PhysicalTable): string {
  const parts = t.columns.map((c) => `  ${columnDefinition(c)}`);
  if (t.primaryKey) {
    const name = t.primaryKey.name ? `CONSTRAINT ${quoteIdent(t.primaryKey.name)} ` : "";
    parts.push(`  ${name}PRIMARY KEY (${columnList(t.primaryKey.columns)})`);
  }
  for (const u of [...t.uniques].sort((a, b) => cmp(a.name, b.name))) {
    parts.push(`  CONSTRAINT ${quoteIdent(u.name)} UNIQUE (${columnList(u.columns)})`);
  }
  for (const c of [...(t.checks ?? [])].sort((a, b) => cmp(a.name, b.name))) {
    parts.push(`  CONSTRAINT ${quoteIdent(c.name)} CHECK (${c.sql})`);
  }
  return `CREATE COLUMN TABLE ${physicalTableRef(t)} (\n${parts.join(",\n")}\n)`;
}

export function dropTableSql(t: { schema?: string; name: string }): string {
  return `DROP TABLE ${physicalTableRef(t)}`;
}

/** `RENAME TABLE`; qualifies the target when the table moves to another schema (HANA supports that). */
export function renameTableSql(from: { schema?: string; name: string }, to: { schema?: string; name: string }): string {
  const target = (from.schema ?? "") === (to.schema ?? "") ? quoteIdent(to.name) : physicalTableRef(to);
  return `RENAME TABLE ${physicalTableRef(from)} TO ${target}`;
}

/** HANA renames indexes but not constraints (no RENAME CONSTRAINT); constraints are dropped and re-added. */
export function renameIndexSql(schema: string | undefined, from: string, to: string): string {
  return `RENAME INDEX ${physicalTableRef({ schema, name: from })} TO ${quoteIdent(to)}`;
}

export function renameColumnSql(t: { schema?: string; name: string }, from: string, to: string): string {
  return `RENAME COLUMN ${physicalTableRef(t)}.${quoteIdent(from)} TO ${quoteIdent(to)}`;
}

export function addColumnSql(t: { schema?: string; name: string }, c: PhysicalColumn): string {
  return `ALTER TABLE ${physicalTableRef(t)} ADD (${columnDefinition(c)})`;
}

export function alterColumnSql(t: { schema?: string; name: string }, c: PhysicalColumn): string {
  return `ALTER TABLE ${physicalTableRef(t)} ALTER (${columnDefinition(c, true)})`;
}

export function dropColumnSql(t: { schema?: string; name: string }, column: string): string {
  return `ALTER TABLE ${physicalTableRef(t)} DROP (${quoteIdent(column)})`;
}

export function addPrimaryKeySql(t: { schema?: string; name: string }, name: string | undefined, columns: readonly string[]): string {
  const n = name ? `CONSTRAINT ${quoteIdent(name)} ` : "";
  return `ALTER TABLE ${physicalTableRef(t)} ADD ${n}PRIMARY KEY (${columnList(columns)})`;
}

export function dropPrimaryKeySql(t: { schema?: string; name: string }): string {
  return `ALTER TABLE ${physicalTableRef(t)} DROP PRIMARY KEY`;
}

export function addUniqueSql(t: { schema?: string; name: string }, name: string, columns: readonly string[]): string {
  return `ALTER TABLE ${physicalTableRef(t)} ADD CONSTRAINT ${quoteIdent(name)} UNIQUE (${columnList(columns)})`;
}

export function dropConstraintSql(t: { schema?: string; name: string }, name: string): string {
  return `ALTER TABLE ${physicalTableRef(t)} DROP CONSTRAINT ${quoteIdent(name)}`;
}

export function createIndexSql(t: { schema?: string; name: string }, name: string, columns: readonly string[]): string {
  return `CREATE INDEX ${physicalTableRef({ schema: t.schema, name })} ON ${physicalTableRef(t)} (${columnList(columns)})`;
}

export function createFulltextIndexSql(t: { schema?: string; name: string }, name: string, column: string): string {
  return `CREATE FULLTEXT INDEX ${physicalTableRef({ schema: t.schema, name })} ON ${physicalTableRef(t)} (${quoteIdent(column)})`;
}

export function dropFulltextIndexSql(schema: string | undefined, name: string): string {
  return `DROP FULLTEXT INDEX ${physicalTableRef({ schema, name })}`;
}

export function dropIndexSql(schema: string | undefined, name: string): string {
  return `DROP INDEX ${physicalTableRef({ schema, name })}`;
}

export function addForeignKeySql(t: { schema?: string; name: string }, fk: PhysicalForeignKey): string {
  return (
    `ALTER TABLE ${physicalTableRef(t)} ADD CONSTRAINT ${quoteIdent(fk.name)} ` +
    `FOREIGN KEY (${columnList(fk.columns)}) REFERENCES ${physicalTableRef({ schema: fk.refSchema, name: fk.refTable })} (${columnList(fk.refColumns)}) ` +
    `ON UPDATE ${fk.onUpdate} ON DELETE ${fk.onDelete}`
  );
}

export function addCheckSql(t: { schema?: string; name: string }, c: PhysicalCheck): string {
  return `ALTER TABLE ${physicalTableRef(t)} ADD CONSTRAINT ${quoteIdent(c.name)} CHECK (${c.sql})`;
}

export function commentOnTableSql(t: { schema?: string; name: string }, comment: string | undefined): string {
  return `COMMENT ON TABLE ${physicalTableRef(t)} IS ${comment ? sqlString(comment) : "NULL"}`;
}

export function commentOnColumnSql(t: { schema?: string; name: string }, column: string, comment: string | undefined): string {
  return `COMMENT ON COLUMN ${physicalTableRef(t)}.${quoteIdent(column)} IS ${comment ? sqlString(comment) : "NULL"}`;
}

export function createSequenceSql(s: PhysicalSequence): string {
  let sql = `CREATE SEQUENCE ${physicalTableRef(s)}`;
  if (s.start !== undefined) sql += ` START WITH ${s.start}`;
  if (s.increment !== undefined) sql += ` INCREMENT BY ${s.increment}`;
  return sql;
}

export function alterSequenceSql(s: PhysicalSequence): string {
  return `ALTER SEQUENCE ${physicalTableRef(s)} INCREMENT BY ${s.increment ?? 1}`;
}

export function dropSequenceSql(s: { schema?: string; name: string }): string {
  return `DROP SEQUENCE ${physicalTableRef(s)}`;
}

/**
 * Canonical form of a check condition for comparison: keywords and unquoted identifiers upper
 * case, whitespace collapsed (and removed next to punctuation), wrapping parentheses removed.
 * String literals and quoted identifiers are kept as written.
 */
export function normalizeCheckSql(sql: string): string {
  let out = "";
  let i = 0;
  while (i < sql.length) {
    const ch = sql[i]!;
    if (ch === "'" || ch === '"') {
      let j = i + 1;
      while (j < sql.length) {
        if (sql[j] === ch) {
          if (sql[j + 1] === ch) j += 2;
          else break;
        } else j++;
      }
      out += sql.slice(i, j + 1);
      i = j + 1;
      continue;
    }
    if (/\s/.test(ch)) {
      if (!out.endsWith(" ")) out += " ";
      i++;
      continue;
    }
    out += ch.toUpperCase();
    i++;
  }
  // no spaces around punctuation and operators (outside literals, which contain no bare spaces here)
  out = out.replace(/ ?([(),=<>!+\-*/|]) ?/g, (m, p: string, offset: number, all: string) => (inLiteral(all, offset) ? m : p)).trim();
  for (;;) {
    if (!out.startsWith("(") || !out.endsWith(")") || !wrapsAll(out)) break;
    out = out.slice(1, -1).trim();
  }
  return out;
}

function inLiteral(s: string, offset: number): boolean {
  let quote: string | null = null;
  for (let i = 0; i < offset; i++) {
    const c = s[i]!;
    if (quote) {
      if (c === quote) quote = null;
    } else if (c === "'" || c === '"') quote = c;
  }
  return quote !== null;
}

/** True when the opening parenthesis at 0 closes at the last character. */
function wrapsAll(s: string): boolean {
  let depth = 0;
  for (let i = 0; i < s.length; i++) {
    if (inLiteral(s, i)) continue;
    if (s[i] === "(") depth++;
    else if (s[i] === ")") {
      depth--;
      if (depth === 0 && i < s.length - 1) return false;
    }
  }
  return depth === 0;
}

// ---- checks -----------------------------------------------------------------

function schemaPredicate(schema: string | undefined, params: (string | number | boolean | null)[]): string {
  if (schema) {
    params.push(schema);
    return "SCHEMA_NAME = ?";
  }
  return "SCHEMA_NAME = CURRENT_SCHEMA";
}

export function tableExistsCheck(t: { schema?: string; name: string }, expectExists: boolean, description: string): Check {
  const params: (string | number | boolean | null)[] = [];
  const where = schemaPredicate(t.schema, params);
  params.push(t.name);
  return { description, sql: `SELECT 1 FROM SYS.TABLES WHERE ${where} AND TABLE_NAME = ?`, params, expect: expectExists ? "nonEmpty" : "empty" };
}

export function columnExistsCheck(t: { schema?: string; name: string }, column: string, expectExists: boolean, description: string): Check {
  const params: (string | number | boolean | null)[] = [];
  const where = schemaPredicate(t.schema, params);
  params.push(t.name, column);
  return {
    description,
    sql: `SELECT 1 FROM SYS.TABLE_COLUMNS WHERE ${where} AND TABLE_NAME = ? AND COLUMN_NAME = ?`,
    params,
    expect: expectExists ? "nonEmpty" : "empty",
  };
}

export function noNullsCheck(t: { schema?: string; name: string }, column: string): Check {
  return {
    description: `column ${quoteIdent(column)} of ${physicalTableRef(t)} has no NULL values`,
    sql: `SELECT 1 FROM ${physicalTableRef(t)} WHERE ${quoteIdent(column)} IS NULL LIMIT 1`,
    expect: "empty",
  };
}

export function sequenceExistsCheck(s: { schema?: string; name: string }, expectExists: boolean, description: string): Check {
  const params: (string | number | boolean | null)[] = [];
  const where = schemaPredicate(s.schema, params);
  params.push(s.name);
  return { description, sql: `SELECT 1 FROM SYS.SEQUENCES WHERE ${where} AND SEQUENCE_NAME = ?`, params, expect: expectExists ? "nonEmpty" : "empty" };
}

/** Rows that violate a check condition (NULL results pass a CHECK, as in SQL). */
export function checkHoldsCheck(t: { schema?: string; name: string }, c: PhysicalCheck): Check {
  return { description: `all rows of ${physicalTableRef(t)} satisfy ${c.sql}`, sql: `SELECT 1 FROM ${physicalTableRef(t)} WHERE NOT (${c.sql}) LIMIT 1`, expect: "empty" };
}

export function tableEmptyCheck(t: { schema?: string; name: string }): Check {
  return { description: `table ${physicalTableRef(t)} is empty`, sql: `SELECT 1 FROM ${physicalTableRef(t)} LIMIT 1`, expect: "empty" };
}

export function noDuplicatesCheck(t: { schema?: string; name: string }, columns: readonly string[]): Check {
  const cols = columnList(columns);
  return {
    description: `no duplicate values in (${cols}) of ${physicalTableRef(t)}`,
    sql: `SELECT 1 FROM ${physicalTableRef(t)} WHERE ${columns.map((c) => `${quoteIdent(c)} IS NOT NULL`).join(" AND ")} GROUP BY ${cols} HAVING COUNT(*) > 1 LIMIT 1`,
    expect: "empty",
  };
}

export function cmp(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}
