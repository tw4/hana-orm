/**
 * Physical schema: the database-level view of tables shared by the planner, `db push`,
 * drift detection and `db pull`. It is built either from a contract
 * (`contractToPhysical`) or from the live catalog (`introspect`), and compared by `diffSchemas`.
 *
 * Table keys: `TABLE` for tables in the default schema, `SCHEMA.TABLE` otherwise. Keeping
 * the default schema implicit lets the same migration run in environments whose default
 * schema differs.
 */

export type FkAction = "CASCADE" | "RESTRICT" | "SET NULL" | "SET DEFAULT";

export interface PhysicalColumn {
  name: string;
  /** Normalized HANA type, e.g. `NVARCHAR(255)`, `DECIMAL(15,2)`, `INTEGER`. */
  type: string;
  nullable: boolean;
  /** Normalized SQL default expression (`'text'`, `42`, `TRUE`, `CURRENT_UTCTIMESTAMP`). */
  default?: string;
  /** `GENERATED BY DEFAULT AS IDENTITY` (or `ALWAYS`, when introspected). */
  identity?: boolean;
}

export interface PhysicalPrimaryKey {
  /** Constraint name; may be a system name (`_SYS_...`) when introspected. */
  name?: string;
  columns: string[];
}

export interface PhysicalUnique {
  name: string;
  columns: string[];
}

export interface PhysicalIndex {
  name: string;
  columns: string[];
}

/** A HANA full-text index on one column. */
export interface PhysicalFulltextIndex {
  name: string;
  column: string;
}

export interface PhysicalForeignKey {
  name: string;
  columns: string[];
  /** Referenced table: undefined schema = default schema. */
  refSchema?: string;
  refTable: string;
  refColumns: string[];
  onDelete: FkAction;
  onUpdate: FkAction;
}

export interface PhysicalTable {
  /** undefined = datasource default schema. */
  schema?: string;
  name: string;
  columns: PhysicalColumn[];
  primaryKey: PhysicalPrimaryKey | null;
  uniques: PhysicalUnique[];
  indexes: PhysicalIndex[];
  foreignKeys: PhysicalForeignKey[];
  fulltext?: PhysicalFulltextIndex[];
  /** Table comment (introspection only). */
  comment?: string;
}

export interface PhysicalViewColumn {
  name: string;
  type: string;
  nullable: boolean;
}

export interface PhysicalView {
  schema?: string;
  name: string;
  columns: PhysicalViewColumn[];
}

export interface PhysicalSchema {
  tables: Record<string, PhysicalTable>;
  /** Only filled by introspection with views enabled; ignored by the diff. */
  views?: Record<string, PhysicalView>;
}

/** HANA identifiers are limited to 127 characters. */
export const MAX_IDENT_LENGTH = 127;

export function tableKey(schema: string | undefined, name: string): string {
  return schema ? `${schema}.${name}` : name;
}

export function keyOf(t: { schema?: string; name: string }): string {
  return tableKey(t.schema, t.name);
}

export function refKeyOf(fk: PhysicalForeignKey): string {
  return tableKey(fk.refSchema, fk.refTable);
}

export function getPhysicalColumn(t: PhysicalTable, name: string): PhysicalColumn | undefined {
  return t.columns.find((c) => c.name === name);
}

/** Deep copy (the structure is plain JSON). */
export function clonePhysical<T>(value: T): T {
  return structuredClone(value);
}

export function emptyPhysical(): PhysicalSchema {
  return { tables: {} };
}

export function sameColumns(a: readonly string[], b: readonly string[]): boolean {
  return a.length === b.length && a.every((x, i) => x === b[i]);
}
