/**
 * `hana-orm generate --sql`: reads `sql/*.sql`, asks HANA to describe each statement (prepare
 * without executing) and writes typed query functions.
 *
 * A file holds one statement. Parameters are `?` (named `p1`, `p2`, … in the generated
 * function) or `:name` (the same name may appear several times; it is one argument).
 */

import { sqlColumnKind, sqlColumnTsType, sqlParamTsType, type SqlColumnKind, type StatementDescription } from "../runtime/typed-sql.ts";

export { describeFromHanaMetadata, type DescribingDriver, type StatementDescription } from "../runtime/typed-sql.ts";
import { splitSqlStatements } from "../migrate/sql-split.ts";

export interface ParsedSqlFile {
  /** Name of the generated function (`get-active-users.sql` → `getActiveUsers`). */
  name: string;
  /** SQL with every parameter as `?`. */
  sql: string;
  /** Argument name for each `?`, in order (a `:name` used twice appears twice). */
  placeholders: string[];
  /** Distinct argument names in order of first use. */
  args: string[];
}

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

export function functionName(fileName: string): string {
  const base = fileName.replace(/\.sql$/i, "");
  const parts = base.split(/[^A-Za-z0-9]+/).filter(Boolean);
  const name = parts.map((p, i) => (i === 0 ? p.charAt(0).toLowerCase() + p.slice(1) : p.charAt(0).toUpperCase() + p.slice(1))).join("");
  if (!IDENT.test(name) || /^\d/.test(name)) throw new Error(`${fileName}: cannot derive a function name; use letters, digits, - or _`);
  return name;
}

/** Turns `:name` parameters into `?` (outside strings, quoted identifiers and comments). */
export function parseSqlFile(fileName: string, text: string): ParsedSqlFile {
  const statements = splitSqlStatements(text);
  if (statements.length !== 1) throw new Error(`${fileName}: expected exactly one SQL statement, found ${statements.length}`);
  const src = statements[0]!;
  let sql = "";
  const placeholders: string[] = [];
  let positional = 0;
  let i = 0;
  while (i < src.length) {
    const c = src[i]!;
    const next = src[i + 1];
    if (c === "'" || c === '"') {
      let j = i + 1;
      while (j < src.length && !(src[j] === c && src[j + 1] !== c)) j += src[j] === c ? 2 : 1;
      sql += src.slice(i, j + 1);
      i = j + 1;
      continue;
    }
    if (c === "-" && next === "-") {
      const j = src.indexOf("\n", i);
      const end = j < 0 ? src.length : j;
      sql += src.slice(i, end);
      i = end;
      continue;
    }
    if (c === "/" && next === "*") {
      const j = src.indexOf("*/", i + 2);
      const end = j < 0 ? src.length : j + 2;
      sql += src.slice(i, end);
      i = end;
      continue;
    }
    if (c === "?") {
      placeholders.push(`p${++positional}`);
      sql += "?";
      i++;
      continue;
    }
    if (c === ":" && next !== undefined && /[A-Za-z_]/.test(next) && src[i - 1] !== ":") {
      const m = /^[A-Za-z_][A-Za-z0-9_]*/.exec(src.slice(i + 1))!;
      placeholders.push(m[0]);
      sql += "?";
      i += 1 + m[0].length;
      continue;
    }
    sql += c;
    i++;
  }
  if (positional && placeholders.some((p) => !/^p\d+$/.test(p))) throw new Error(`${fileName}: use either ? or :name parameters, not both`);
  const args = [...new Set(placeholders)];
  for (const a of args) if (!IDENT.test(a)) throw new Error(`${fileName}: invalid parameter name '${a}'`);
  return { name: functionName(fileName), sql, placeholders, args };
}

/** Source of the generated module. */
export function generateTypedSqlModule(entries: { file: ParsedSqlFile; description: StatementDescription }[], runtimeImport = "hana-orm/runtime"): string {
  const out: string[] = [];
  out.push("// Generated by hana-orm from sql/*.sql. Do not edit: run `hana-orm generate --sql` after changing a query.");
  out.push("/* eslint-disable */");
  out.push(`import * as $r from "${runtimeImport}";`, "");
  const names = new Set<string>();
  for (const { file, description } of entries) {
    if (names.has(file.name)) throw new Error(`Two SQL files produce the function name '${file.name}'`);
    names.add(file.name);
    if (description.params.length !== file.placeholders.length) {
      throw new Error(`${file.name}: HANA reports ${description.params.length} parameter(s), the file has ${file.placeholders.length}`);
    }
    const columns: Record<string, SqlColumnKind> = {};
    const fields: string[] = [];
    for (const c of description.columns) {
      if (c.name in columns) throw new Error(`${file.name}: the result has two columns named '${c.name}'; give them distinct aliases`);
      const kind = sqlColumnKind(c.typeName);
      columns[c.name] = kind;
      fields.push(`${JSON.stringify(c.name)}: ${sqlColumnTsType(kind)}${c.nullable ? " | null" : ""}`);
    }
    // an argument takes the type of its first placeholder
    const argType = new Map<string, string>();
    file.placeholders.forEach((p, i) => {
      if (!argType.has(p)) argType.set(p, sqlParamTsType(sqlColumnKind(description.params[i]!.typeName)));
    });
    const Row = `${file.name.charAt(0).toUpperCase()}${file.name.slice(1)}Row`;
    out.push(`export type ${Row} = { ${fields.join("; ")} };`);
    out.push(`/** \`${file.sql.replace(/\s+/g, " ").replace(/\*\//g, "* /").slice(0, 200)}\` */`);
    out.push(
      `export function ${file.name}(${file.args.map((a) => `${a}: ${argType.get(a)} | null`).join(", ")}): $r.TypedSql<${Row}> {`,
      `  return $r.typedSql<${Row}>(${JSON.stringify(file.sql)}, [${file.placeholders.join(", ")}], ${JSON.stringify(columns)});`,
      "}",
      "",
    );
  }
  return out.join("\n");
}
